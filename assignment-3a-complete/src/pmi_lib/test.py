def pathfinder(filename: str) -> str | None:
    """Find the first matching file or directory below the current directory."""
    for root, directories, files in os.walk(os.getcwd()):
        if filename in files or filename in directories:
            return os.path.join(root, filename)
    return None


def test(
    path_dicom: str,
    path_new_nifti: str,
    sigma: tuple[float, ...] = (1.0, 1.0, 1.0),
) -> None:
    """Demonstrate the Assignment 2A/2B readers, writer, and Gaussian filter."""
    print("===read_dicom===")
    image_dicom = read_dicom(path_dicom)
    print("DICOM image read by read_dicom, viewed with pmi_viewer\n")
    view(image_dicom._data, spacing=image_dicom.spacing)

    data = image_dicom._data
    spacing = image_dicom.spacing
    metadata = image_dicom.metadata
    im1 = Image(data, spacing)
    print("=== Image Info ===")
    print(im1)
    print(f"Pixel Area: {im1.get_pixel_area()} mm^2")
    if data.ndim >= 3:
        print(f"Voxel Volume: {im1.get_voxel_volume()} mm^3")

    if metadata is None:
        metadata = {"PatientName": "Jan Jansen", "PatientID": "123"}
    im_dicom = DicomImage(data, spacing, metadata)
    print("\n=== DicomImage Info ===")
    print(f"DICOM metadata: {len(im_dicom.metadata)} attributes")

    print("\n===dicom_to_nifti===")
    dicom_to_nifti(path_dicom, path_new_nifti)
    image_new_nifti = read_nifti(path_new_nifti)
    print("NIfTI image generated by dicom_to_nifti and read by read_nifti")
    view(image_new_nifti._data, spacing=image_new_nifti.spacing)

    print("\n===masked_gaussian_filter===")
    mask = Image(image_new_nifti._data > 0, spacing=image_new_nifti.spacing)
    gauss = masked_gaussian_filter(image_new_nifti, mask, sigma)
    print("Gaussian filter applied over data of NIfTI image")
    view(gauss._data, spacing=gauss.spacing)


def test_filters() -> None:
    """Print the mean squared difference between the Python and C filters."""
    noise = np.random.randn(50, 100)
    image = Image(noise, spacing=(1.0, 2.0))
    add_sphere(image, radius=30.0, value=10.0)

    result_py = bilateral_filter_py(image, sigma_s=5.0, sigma_r=2.0)
    result_c = bilateral_filter(image, sigma_s=5.0, sigma_r=2.0)
    mean_squared_difference = np.mean(
        (np.asarray(result_py) - np.asarray(result_c)) ** 2
    )
    print(f"Mean squared difference: {mean_squared_difference}")


def test_spheres() -> None:
    """Print pairwise differences between Python, NumPy, and C spheres."""
    # Array and spacing axes use the same (z, y, x) order.
    shape = (9, 17, 21)
    spacing = (2.5, 1.25, 0.75)
    spheres = ((2.5, 3.0), (4.0, -1.5), (3.0, 2.0))
    implementations = (add_sphere_py, add_sphere_np, add_sphere)
    images = [
        Image(np.zeros(shape, dtype=np.float64), spacing=spacing)
        for _ in implementations
    ]

    for image, implementation in zip(images, implementations):
        for radius, value in spheres:
            implementation(image, radius=radius, value=value)

    pairs = (
        ("Python / NumPy", images[0], images[1]),
        ("Python / C", images[0], images[2]),
        ("NumPy / C", images[1], images[2]),
    )
    for label, first, second in pairs:
        mean_squared_difference = np.mean(
            (np.asarray(first) - np.asarray(second)) ** 2
        )
        print(f"Mean squared difference ({label}): {mean_squared_difference}")
